AIC_CORE_MAX_NUM = 36
MQSMLA_METADATA_TOTAL_SIZE = 1024
FA_METADATA_SIZE = 9
FA_CORE_ENABLE_INDEX = 0
FA_BN2_START_INDEX = 1
FA_M_START_INDEX = 2
FA_S2_START_INDEX = 3
FA_BN2_END_INDEX = 4
FA_M_END_INDEX = 5
