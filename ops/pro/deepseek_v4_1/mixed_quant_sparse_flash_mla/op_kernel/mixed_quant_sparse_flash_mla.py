def _pair_vals(tab, idx):
    """Read two int64 addresses at ``idx``/``idx+1`` and return (min, gap)."""
    a0 = pl.getval(tab, idx)
    a1 = pl.getval(tab, idx + 1)
    lo = pl.min(a0, a1)
    return lo, pl.max(a0, a1) - lo


