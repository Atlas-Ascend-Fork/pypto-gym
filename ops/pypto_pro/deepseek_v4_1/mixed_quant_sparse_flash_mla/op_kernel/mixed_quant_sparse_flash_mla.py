    m_first = ctx.m_first
    m_last = ctx.m_last
    k_ori = ctx.k_ori
    k_cmp = ctx.k_cmp
    s2_s = ctx.s2_s
    s2_e = ctx.s2_e
    h_ws = ctx.h_ws
    t_ws = ctx.t_ws
    ln_o_c = ctx.ln_o_c
    ln_c_c = ctx.ln_c_c
    t_m = m_first + t_ms
    t_wo = k_ori
    if HAS_ORI_LEN == 1:
        t_wo = pl.getval(ln_o_c, t_m)
        t_wo = pl.min(k_ori, pl.max(t_wo, 0))
    idiv_17 = t_wo // 128
    idiv_18 = t_wo % 128
    idiv_19 = idiv_18 != 0
    idiv_20 = t_wo < 0
    idiv_22 = idiv_20 == 0
    idiv_23 = idiv_19 & idiv_22
    idiv_24 = 1 if idiv_23 else 0
    t_ot = idiv_17 + idiv_24
    t_wc = 0
    if HAS_CMP == 1:
        if HAS_CMP_LEN == 1:
            t_wc = pl.getval(ln_c_c, t_m)
            t_wc = pl.min(k_cmp, pl.max(t_wc, 0))
        else:
            t_wc = k_cmp
    idiv_25 = t_wc // 128
    idiv_26 = t_wc % 128
    idiv_27 = idiv_26 != 0
    idiv_28 = t_wc < 0
    idiv_30 = idiv_28 == 0
    idiv_31 = idiv_27 & idiv_30
    idiv_32 = 1 if idiv_31 else 0
    t_ct = idiv_25 + idiv_32
    t_tls = t_ot + t_ct
    t_tlf = 0
    t_thf = t_tls + pl.get_block_idx() * 0
    twsf = 0
    if t_m == m_first:
        t_tlf = s2_s + pl.get_block_idx() * 0
        if s2_s > 0:
            twsf = h_ws + pl.get_block_idx() * 0
    if t_m == m_last:
        if s2_e > 0:
            t_thf = s2_e + pl.get_block_idx() * 0
            twsf = t_ws + pl.get_block_idx() * 0


