@pl.vector_function
def fd_merge_chunk_vf(o0, o1, m0, m1, l0, l1, outc, cc):
    _pall_f32 = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=pl.DT_FP32)
    vf.mem_bar(mode=pl.MemBarMode.VST_VLD)
    dummy = vf.full(0, dtype=pl.DT_BF16)
    lh = vf.create_mask(pattern=pl.MaskPattern.H, dtype=pl.DT_FP16)
    one = vf.full(1.0, dtype=pl.DT_FP32)
    for h in pl.range(0, 32, 1):
        m0v = vf.load_align(m0, [0, h], dist=pl.LoadDist.BRC_B32)
        m1v = vf.load_align(m1, [0, h], dist=pl.LoadDist.BRC_B32)
        av = vf.exp_sub(m0v, m1v, _pall_f32)
        l0v = vf.load_align(l0, [0, h], dist=pl.LoadDist.BRC_B32)
        l1v = vf.load_align(l1, [0, h], dist=pl.LoadDist.BRC_B32)
        dv = vf.mul(l0v, av, _pall_f32)
        dv = vf.add(dv, l1v, _pall_f32)
        iv = vf.div(one, dv, _pall_f32)
        mul = h * 128
        r0 = vf.load_align(o0, mul)
        r1 = vf.load_align(o1, mul)
        r0 = vf.mul(r0, av, _pall_f32)
        r0 = vf.add(r0, r1, _pall_f32)
        r0 = vf.mul(r0, iv, _pall_f32)
        b128 = vf.astype(r0, _pall_f32, dtype=pl.DT_BF16, saturate=pl.SaturateMode.OFF)
        b64, dummy = vf.de_interleave(b128, dummy)
        add_6 = (h * 512) + (cc * 128)
        vf.store_align(outc + add_6, b64, lh, data_copy_mode=pl.DataCopyMode.DATA_BLOCK_COPY, block_stride=1)
        add_8 = mul + 64
        r0 = vf.load_align(o0, add_8)
        r1 = vf.load_align(o1, add_8)
        r0 = vf.mul(r0, av, _pall_f32)
        r0 = vf.add(r0, r1, _pall_f32)
        r0 = vf.mul(r0, iv, _pall_f32)
        b128 = vf.astype(r0, _pall_f32, dtype=pl.DT_BF16, saturate=pl.SaturateMode.OFF)
        b64, dummy = vf.de_interleave(b128, dummy)
        vf.store_align(outc + (add_6 + 64), b64, lh, data_copy_mode=pl.DataCopyMode.DATA_BLOCK_COPY, block_stride=1)


@pl.vector_function
def fd_lse_vf(m0, m1, l0, l1, lset):
    _pall_f32 = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=pl.DT_FP32)
    vf.mem_bar(mode=pl.MemBarMode.VST_VLD)
    m0v = vf.load_align(m0, 0)
    m1v = vf.load_align(m1, 0)
    av = vf.exp_sub(m0v, m1v, _pall_f32)
    l0v = vf.load_align(l0, 0)
    l1v = vf.load_align(l1, 0)
    dv = vf.mul(l0v, av, _pall_f32)
    dv = vf.add(dv, l1v, _pall_f32)
    lg = vf.ln(dv, _pall_f32)
    dv = vf.add(lg, m1v, _pall_f32)
    vf.store_align(lset, dv, _pall_f32, data_copy_mode=pl.DataCopyMode.DATA_BLOCK_COPY, block_stride=1)


