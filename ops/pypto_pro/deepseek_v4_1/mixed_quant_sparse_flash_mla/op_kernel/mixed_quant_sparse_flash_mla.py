@pl.vector_function
def tile_exp_vf(su, pnz, tsum, m_buf, valid_n):
    _pall_f32 = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=pl.DT_FP32)
    vf.mem_bar(mode=pl.MemBarMode.VST_VLD)
    dummy = vf.full(0, dtype=pl.DT_BF16)
    m64 = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=pl.DT_FP32)
    lh = vf.create_mask(pattern=pl.MaskPattern.H, dtype=pl.DT_FP16)
    pm1 = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=pl.DT_FP32)
    pm2 = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=pl.DT_FP32)
    c1 = valid_n
    if c1 > 64:
        c1 = 64
    c2 = valid_n - 64
    if c2 < 0:
        c2 = 0
    pm1 = vf.update_mask(c1, dtype=pl.DT_FP32)
    pm2 = vf.update_mask(c2, dtype=pl.DT_FP32)
    ureg = vf.unalign_reg_for_store()
    for h in pl.range(0, 32, 1):
        mb = vf.load_align(m_buf, [0, h], dist=pl.LoadDist.BRC_B32)
        mul = h * 128
        s0 = vf.load_align(su, mul)
        s1 = vf.load_align(su, (mul + 64))
        e0 = vf.exp_sub(s0, mb, pm1)
        e1 = vf.exp_sub(s1, mb, pm2)
        acc = vf.add(e0, e1, _pall_f32)
        ps = vf.reduce_sum(acc, m64)
        vf.store_unalign(tsum, ps, ureg, 1, post_update=True)
        b128 = vf.astype(e0, _pall_f32, dtype=pl.DT_BF16, saturate=pl.SaturateMode.OFF)
        b64, dummy = vf.de_interleave(b128, dummy)
        mul_2 = h * 16
        vf.store_align(pnz + mul_2, b64, lh, data_copy_mode=pl.DataCopyMode.DATA_BLOCK_COPY, block_stride=33)
        b128 = vf.astype(e1, _pall_f32, dtype=pl.DT_BF16, saturate=pl.SaturateMode.OFF)
        b64, dummy = vf.de_interleave(b128, dummy)
        vf.store_align(pnz + (mul_2 + 2112), b64, lh, data_copy_mode=pl.DataCopyMode.DATA_BLOCK_COPY, block_stride=33)
    vf.store_unalign_post(tsum, ureg, 0, post_update=True)
    vf.mem_bar(mode=pl.MemBarMode.VST_VLD)


