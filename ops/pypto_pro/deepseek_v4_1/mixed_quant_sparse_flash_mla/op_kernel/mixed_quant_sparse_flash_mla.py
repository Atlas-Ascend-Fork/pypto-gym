def _planned_blocks(metadata):
    """Launched core count = the metadata's highest enabled FA slot + 1."""
    enable = metadata.reshape(-1)[: FA_METADATA_SIZE * AIC_CORE_MAX_NUM].tolist()
    n = 1
    for core in range(AIC_CORE_MAX_NUM):
        if enable[FA_METADATA_SIZE * core] != 0:
            n = core + 1
    return max(1, min(AIC_CORE_MAX_NUM, n))


def _tiling_key(tensors, fd_enable=None):
    """Compile-time code-path conditions (see ``MqsmlaTilingKey``)."""
    has_cmp = isinstance(tensors.get("cmp_kv"), torch.Tensor)
    has_ori_len = isinstance(tensors.get("ori_topk_length"), torch.Tensor)
    has_cmp_len = has_cmp and isinstance(tensors.get("cmp_topk_length"), torch.Tensor)
    if fd_enable is None:
        md = tensors.get("metadata")
        fd_enable = int(md.reshape(-1)[900].item()) if isinstance(md, torch.Tensor) else 0
    return {
        "HAS_ORI_LEN": int(bool(has_ori_len)),
        "HAS_CMP_LEN": int(bool(has_cmp_len)),
        "HAS_CMP": int(bool(has_cmp)),
        "FD_ENABLE": int(bool(fd_enable)),
    }


def _runtime_args(tensors, softmax_scale):
    """Runtime scalars (order matches the kernel signature tail)."""
    cmp_kv = tensors.get("cmp_kv")
    cmp_idx = tensors.get("cmp_sparse_indices")
    cmp_bt = tensors.get("cmp_block_table")
    return [
        float(softmax_scale),
        int(tensors["ori_kv"].stride(0)),  # ori page stride
        int(cmp_kv.stride(0)) if isinstance(cmp_kv, torch.Tensor) else 0,
        int(tensors["cu_seqlens_q"].shape[0]),  # b_num = B + 1
        int(tensors["ori_sparse_indices"].shape[2]),  # k_ori
        int(cmp_idx.shape[2]) if isinstance(cmp_idx, torch.Tensor) else 129,
        int(tensors["ori_kv"].shape[1]),  # bs_ori
        int(cmp_kv.shape[1]) if isinstance(cmp_kv, torch.Tensor) else 128,
        int(tensors["ori_block_table"].shape[1]),  # bt_ori
        int(cmp_bt.shape[1]) if isinstance(cmp_bt, torch.Tensor) else 0,
    ]


def _check_tensors(tensors):
    for name in (
        "q",
        "ori_kv",
        "ori_sparse_indices",
        "ori_block_table",
        "sinks",
        "metadata",
        "cu_seqlens_q",
        "out",
        "lse",
    ):
        if not isinstance(tensors.get(name), torch.Tensor):
            raise ValueError(f"input {name} must be a torch.Tensor")
    if isinstance(tensors.get("cmp_kv"), torch.Tensor):
        for name in ("cmp_sparse_indices", "cmp_block_table"):
            if not isinstance(tensors.get(name), torch.Tensor):
                raise ValueError(f"cmp_kv is given but {name} is missing")


def mixed_quant_sparse_flash_mla_metadata(
    ori_topk_length,
    cmp_topk_length,
    *,
    cu_seqlens_q=None,
    num_heads_q=64,
    num_heads_kv=1,
    head_dim=512,
    quant_mode=1,
    has_cmp_kv=True,
    block_num=None,
):
    """Host-side metadata planner -> ``int32[1024]`` (see README.md).

    Reads the per-query TopK lengths / ``cu_seqlens_q`` on the host (D2H) and
    plans the whole-row (uniform) or flat ``(row, tile)`` FlashDecode schedule.
    ``cu_seqlens_q`` defaults to a single batch ``[0, T1]``.
    """
    if quant_mode != 1:
        raise ValueError("quant_mode must be 1")
    if (int(num_heads_q), int(num_heads_kv), int(head_dim)) != (64, 1, 512):
        raise ValueError("only num_heads_q=64, num_heads_kv=1, head_dim=512 are supported")
    if not isinstance(ori_topk_length, torch.Tensor) or not isinstance(cmp_topk_length, torch.Tensor):
        raise ValueError("ori_topk_length and cmp_topk_length must be torch.Tensor")
    rows = int(ori_topk_length.reshape(-1).numel())
    if cu_seqlens_q is None:
        cu_q = torch.tensor([0, rows], dtype=torch.int32, device=ori_topk_length.device)
    else:
        cu_q = cu_seqlens_q
    md, _blocks = build_metadata(cu_q, ori_topk_length, cmp_topk_length, has_cmp=bool(has_cmp_kv), blocks=block_num)
    return md


def mixed_quant_sparse_flash_mla(
    q,
    *,
    ori_kv,
    ori_sparse_indices,
    ori_block_table,
    cu_seqlens_q,
    sinks,
    metadata,
    quant_mode=1,
    softmax_scale=None,
    cmp_kv=None,
    cmp_sparse_indices=None,
    cmp_block_table=None,
    ori_topk_length=None,
    cmp_topk_length=None,
    seqused_q=None,
    seqused_ori_kv=None,
    seqused_cmp_kv=None,
    layout_q="TND",
    layout_kv="PA_BBND",
    return_softmax_lse=False,
    out=None,
    lse=None,
    block_dim=None,
    fd_enable=None,
):
    """Sparse mixed-quant Flash MLA (single ``@pl.jit`` CV-fused kernel).

    Contract and shapes are documented in ``README.md``. Optional inputs pass as
    ``None``: absent ``*_topk_length`` means the whole K column range is valid,
    and an absent cmp group (``cmp_kv``/``cmp_sparse_indices``/``cmp_block_table``)
    turns the cmp arm off. ``out``/``lse`` are allocated with ``torch.empty`` when
    not supplied. ``block_dim`` defaults to the metadata's planned core count;
    ``fd_enable`` defaults to the metadata plan word ``[900]``.

    Returns ``{"out": out, "lse": lse}`` (the kernel always writes LSE).
    """
    if quant_mode != 1:
        raise ValueError("quant_mode must be 1")
    if layout_q != "TND" or layout_kv != "PA_BBND":
        raise ValueError("only layout_q='TND', layout_kv='PA_BBND' are supported")
    for name, tensor in (
        ("seqused_q", seqused_q),
        ("seqused_ori_kv", seqused_ori_kv),
        ("seqused_cmp_kv", seqused_cmp_kv),
    ):
        if tensor is not None and not isinstance(tensor, torch.Tensor):
            raise ValueError(f"{name} must be a torch.Tensor or None")
    if not isinstance(q, torch.Tensor):
        raise ValueError("q must be a torch.Tensor")
    head_dim = int(q.shape[-1])
    scale = float(softmax_scale) if softmax_scale is not None else 1.0 / math.sqrt(head_dim)
    if out is None:
        out = torch.empty(tuple(q.shape), dtype=torch.bfloat16, device=q.device)
    if lse is None:
        lse = torch.empty((1, int(q.shape[0]), int(q.shape[1])), dtype=torch.float32, device=q.device)
    tensors = dict(
        q=q,
        ori_kv=ori_kv,
        ori_sparse_indices=ori_sparse_indices,
        ori_block_table=ori_block_table,
        ori_topk_length=ori_topk_length,
        sinks=sinks,
        metadata=metadata,
        cmp_kv=cmp_kv,
        cmp_sparse_indices=cmp_sparse_indices,
        cmp_block_table=cmp_block_table,
        cmp_topk_length=cmp_topk_length,
        cu_seqlens_q=cu_seqlens_q,
        out=out,
        lse=lse,
    )
    _check_tensors(tensors)
    if block_dim is None:
        block_dim = _planned_blocks(metadata)
    key = _tiling_key(tensors, fd_enable)
    # FlashDecode split partials workspace (fixed size; used only when FD is on).
    ws = torch.zeros(MQSMLA_WORKSPACE_BYTES, dtype=torch.uint8, device=q.device)
    args = [tensors[n] for n in ARG_ORDER] + [ws]
    mixed_quant_sparse_flash_mla_kernel[None, int(block_dim), key](*args, *_runtime_args(tensors, scale))
    return {"out": out, "lse": lse}
