@pl.vector_function
def tile_max_vf(su, tmax, scale, valid_n):
    _pall_f32 = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=pl.DT_FP32)
    vf.mem_bar(mode=pl.MemBarMode.VST_VLD)
    ureg = vf.unalign_reg_for_store()
    tail16 = valid_n
    if tail16 <= 16:
        pm1 = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=pl.DT_FP32)
        c1 = valid_n
        pm1 = vf.update_mask(c1, dtype=pl.DT_FP32)
        for h in pl.range(0, 32, 1):
            mul = h * 128
            r01_0 = vf.load_align(su, mul)
            r01_1 = vf.load_align(su, (mul + 64))
            r01_0 = vf.muls(r01_0, scale, _pall_f32)
            r01_1 = vf.muls(r01_1, scale, _pall_f32)
            vf.store_align(su, r01_0, _pall_f32, [h, 0])
            vf.store_align(su, r01_1, _pall_f32, [h, 64])
            mx = vf.reduce_max(r01_0, pm1)
            vf.store_unalign(tmax, mx, ureg, 1, post_update=True)
    else:
        for h_1 in pl.range(0, 32, 1):
            mul_1 = h_1 * 128
            r01_0 = vf.load_align(su, mul_1)
            r01_1 = vf.load_align(su, (mul_1 + 64))
            r01_0 = vf.muls(r01_0, scale, _pall_f32)
            r01_1 = vf.muls(r01_1, scale, _pall_f32)
            vf.store_align(su, r01_0, _pall_f32, [h_1, 0])
            vf.store_align(su, r01_1, _pall_f32, [h_1, 64])
            tmp = vf.max(r01_0, r01_1, _pall_f32)
