@pl.vector_function
def softmax_vf(su, pnz, tsum, tmax, m_buf, al_buf, valid_n, scale):
    _pall_f32 = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=pl.DT_FP32)
    vf.mem_bar(mode=pl.MemBarMode.VST_VLD)
    _pall_bf16 = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=pl.DT_BF16)
    m64 = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=pl.DT_FP32)
    pm_e = vf.update_mask((valid_n + 1) // 2, dtype=pl.DT_FP32)
    c_o = valid_n // 2
    if c_o < 0:
        c_o = 0
    pm_o = vf.update_mask(c_o, dtype=pl.DT_FP32)
    ureg_m = vf.unalign_reg_for_store()
    ureg_s = vf.unalign_reg_for_store()
    tail16 = valid_n
    if tail16 <= 16:
        pm1 = vf.update_mask(valid_n, dtype=pl.DT_FP32)
        for h in pl.range(0, 32, 1):
            mul = h * 128
            r01_0 = vf.load_align(su, mul)
            r01_1 = vf.load_align(su, (mul + 64))
            r01_0 = vf.muls(r01_0, scale, _pall_f32)
            r01_1 = vf.muls(r01_1, scale, _pall_f32)
            vf.store_align(su, r01_0, _pall_f32, [h, 0])
            vf.store_align(su, r01_1, _pall_f32, [h, 64])
            mx = vf.reduce_max(r01_0, pm1)
            vf.store_unalign(tmax, mx, ureg_m, 1, post_update=True)
    else:
        for h_1 in pl.range(0, 32, 1):
            mul_1 = h_1 * 128
            r01_0 = vf.load_align(su, mul_1)
            r01_1 = vf.load_align(su, (mul_1 + 64))
            r01_0 = vf.muls(r01_0, scale, _pall_f32)
            r01_1 = vf.muls(r01_1, scale, _pall_f32)
            vf.store_align(su, r01_0, _pall_f32, [h_1, 0])
            vf.store_align(su, r01_1, _pall_f32, [h_1, 64])
            tmp = vf.max(r01_0, r01_1, _pall_f32)
            mx = vf.reduce_max(tmp, _pall_f32)
            vf.store_unalign(tmax, mx, ureg_m, 1, post_update=True)
    vf.store_unalign_post(tmax, ureg_m, 0, post_update=True)
    mo = vf.load_align(m_buf, 0)
    vf.mem_bar(mode=pl.MemBarMode.VST_VLD)
    tn = vf.load_align(tmax, 0)
    mn = vf.max(mo, tn, _pall_f32)
    vf.store_align(m_buf, mn, _pall_f32, data_copy_mode=pl.DataCopyMode.DATA_BLOCK_COPY, block_stride=1)
    a = vf.exp_sub(mo, mn, _pall_f32)
    vf.store_align(al_buf, a, _pall_f32, data_copy_mode=pl.DataCopyMode.DATA_BLOCK_COPY, block_stride=1)
    vf.mem_bar(mode=pl.MemBarMode.VST_VLD)
    for h in pl.range(0, 32, 1):
        mb = vf.load_align(m_buf, [0, h], dist=pl.LoadDist.BRC_B32)
        mul = h * 128
        ve, vo = vf.load_align(su, mul, dist=pl.LoadDist.DINTLV_B32)
        e_ve = vf.exp_sub(ve, mb, pm_e)
        e_vo = vf.exp_sub(vo, mb, pm_o)
        acc = vf.add(e_ve, e_vo, _pall_f32)
        ps = vf.reduce_sum(acc, m64)
        vf.store_unalign(tsum, ps, ureg_s, 1, post_update=True)
        he = vf.astype(e_ve, _pall_f32, dtype=pl.DT_BF16, layout=pl.CastLayout.ZERO, saturate=pl.SaturateMode.OFF)
        ho = vf.astype(e_vo, _pall_f32, dtype=pl.DT_BF16, layout=pl.CastLayout.ONE, saturate=pl.SaturateMode.OFF)
        pv = vf.or_(he, ho, _pall_bf16)
        mul_2 = h * 16
        vf.store_align(pnz + mul_2, pv, _pall_bf16, data_copy_mode=pl.DataCopyMode.DATA_BLOCK_COPY, block_stride=33)
    vf.store_unalign_post(tsum, ureg_s, 0, post_update=True)
    vf.mem_bar(mode=pl.MemBarMode.VST_VLD)


@pl.vector_function
def update_l_vf(l_buf, al_buf, tsum):
    _pall_f32 = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=pl.DT_FP32)
    vf.mem_bar(mode=pl.MemBarMode.VST_VLD)
    l = vf.load_align(l_buf, 0)
    a = vf.load_align(al_buf, 0)
